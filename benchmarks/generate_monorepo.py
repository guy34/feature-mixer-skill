#!/usr/bin/env python3
"""Generate a seeded synthetic monorepo for the large-repository robustness test (Phase 5, test P).

Usage:
    python3 benchmarks/generate_monorepo.py OUT_DIR [--scale 1] [--seed 7]

What it contains (scale 1, about 1,100 files; --scale multiplies the bulk):
  apps/web, apps/admin          two React front ends (React 18 and React 17: a version conflict inside one repo)
  services/api                  a Python service (requirements.txt), with generated client code (@generated)
  services/billing              a Go service (go.mod)
  services/search               a Rust service (Cargo.toml)
  packages/ui, packages/utils   shared workspace packages (@mono/ui, @mono/utils), imported by the apps
  db/main.sql, db/analytics.sql two database schemas
  legacy/soap                   an old Java module, marked deprecated
  third_party/other-app         an unrelated application with its own .git: a separate repository
  pnpm-workspace.yaml, package.json   the workspace root
Everything is fictional and identical for a given seed.
"""

import argparse
import json
import os
import random


def write(root, rel, text):
    path = os.path.join(root, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text if isinstance(text, str) else json.dumps(text, indent=2))


def generate(out, scale=1, seed=7):
    rnd = random.Random(seed)
    write(out, "package.json", {"name": "mono", "private": True, "workspaces": ["apps/*", "packages/*"]})
    write(out, "pnpm-workspace.yaml", "packages:\n  - apps/*\n  - packages/*\n")
    write(out, "README.md", "# Mono\n\nWeb, admin, API, billing and search, plus shared packages.\n")
    for pkg in ("ui", "utils"):
        write(out, f"packages/{pkg}/package.json", {"name": f"@mono/{pkg}", "version": "1.0.0"})
        write(out, f"packages/{pkg}/index.ts", f"export const {pkg} = '{pkg}';\n")
        for i in range(40 * scale):
            write(out, f"packages/{pkg}/src/part{i}.ts", f"export const p{i} = {i};\n")
    for app, react in (("web", "^18.2.0"), ("admin", "^17.0.2")):
        write(out, f"apps/{app}/package.json", {"name": app, "dependencies": {"react": react,
                                                                              "@mono/ui": "workspace:*"}})
        write(out, f"apps/{app}/tsconfig.json", {"compilerOptions": {"baseUrl": ".", "paths": {"@/*": ["src/*"]}}})
        for i in range(220 * scale):
            imp = "import { ui } from '@mono/ui';\n" if i % 3 == 0 else "import { helper } from '@/lib/helper';\n"
            write(out, f"apps/{app}/src/screens/s{i}.tsx", imp + f"export default function S{i}() {{ return null; }}\n")
        write(out, f"apps/{app}/src/lib/helper.ts", "export const helper = 1;\n")
        write(out, f"apps/{app}/src/__generated__/graphql.ts", "// @generated by codegen. DO NOT EDIT.\nexport {};\n")
    write(out, "services/api/requirements.txt", "fastapi>=0.110,<1\nsqlalchemy>=2\n")
    for i in range(200 * scale):
        write(out, f"services/api/app/routes/r{i}.py", "from app.models import base\nimport fastapi\n\n"
                                                      f"def handler_{i}():\n    return {i}\n")
    write(out, "services/api/app/__init__.py", "")
    write(out, "services/api/app/models/__init__.py", "")
    write(out, "services/api/app/models/base.py", "import sqlalchemy\n")
    for i in range(60 * scale):
        write(out, f"services/api/gen/client_{i}.py", f"# @generated from openapi.yaml; DO NOT EDIT\nX = {i}\n")
    write(out, "services/billing/go.mod", "module example.com/mono/billing\n\ngo 1.22\n\nrequire github.com/stripe/stripe-go/v76 v76.1.0\n")
    for i in range(120 * scale):
        write(out, f"services/billing/internal/h{i}.go", 'package internal\n\nimport (\n\t"fmt"\n'
                                                         '\t"example.com/mono/billing/internal/db"\n)\n')
    write(out, "services/search/Cargo.toml", '[package]\nname = "search"\n\n[dependencies]\nserde = "1.0"\n')
    for i in range(80 * scale):
        write(out, f"services/search/src/m{i}.rs", "use serde::Serialize;\nuse crate::index;\n")
    write(out, "db/main.sql", "CREATE TABLE users (id uuid primary key, email text unique not null);\n"
                              "CREATE TABLE invoices (id bigserial primary key, user_id uuid references users(id));\n")
    write(out, "db/analytics.sql", "CREATE TABLE events (id bigint primary key, user_id text, at timestamptz);\n")
    write(out, "legacy/soap/README.md", "Deprecated SOAP gateway. Do not extend.\n")
    for i in range(60 * scale):
        write(out, f"legacy/soap/src/main/java/com/mono/soap/Svc{i}.java",
              "package com.mono.soap;\nimport javax.xml.soap.SOAPMessage;\nimport org.apache.axis.Client;\n")
    write(out, "third_party/other-app/.git/HEAD", "ref: refs/heads/main\n")
    write(out, "third_party/other-app/package.json", {"name": "other", "dependencies": {"react": "^16.0.0"}})
    for i in range(50 * scale):
        write(out, f"third_party/other-app/src/x{i}.js", "require('left-pad');\n")
    rnd.random()  # the seed is kept for future randomised content
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate the synthetic monorepo.")
    ap.add_argument("out")
    ap.add_argument("--scale", type=int, default=1)
    ap.add_argument("--seed", type=int, default=7)
    a = ap.parse_args(argv)
    generate(a.out, a.scale, a.seed)
    n = sum(len(f) for _, _, f in os.walk(a.out))
    print(f"wrote {n} files to {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
